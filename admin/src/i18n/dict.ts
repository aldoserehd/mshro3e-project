export type Dict = typeof dict.ar;
export type DictKey = keyof Dict;

export function getDict(locale: Locale = 'ar'): Dict {
  return dict[locale] as Dict;
}

/** Replace `{n}` placeholders. */
export function tFmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
